/**
 * Channel create/update validation. Each provider needs different identifiers
 * and secrets (ARCHITECTURE §4); this module turns an admin's input into the
 * values stored on the row, generating inbound secrets server-side where the
 * provider lets us choose them (returned once to the admin, never again).
 */
import { z } from "zod";
import { CHANNEL_TYPES, type ChannelType } from "@/lib/shared/types";
import { badRequest, unprocessable } from "../api/handler";
import { newToken } from "../crypto";
import { whatsappAppSecret } from "../env";
import { telegramBotId } from "./adapters/telegram";
import { LEGACY_TELEGRAM_CONFIG_KEYS, LEGACY_TELEGRAM_SECRET_KEYS, SECRET_NAMES, type ChannelSecrets } from "./registry";
import { cleanStr } from "./util";

export const MAX_CHANNELS_PER_WORKSPACE = 50;
const MAX_CONFIG_BYTES = 8 * 1024;

/** Secrets Infera can generate (the provider is told the value, not the other way round). */
export const GENERATABLE_SECRETS = ["verifyToken", "webhookSecret", "inboundSecret"] as const;

const nameSchema = z
  .string()
  .max(500)
  .transform((v) => cleanStr(v, 80))
  .pipe(z.string().min(1, "Give the channel a name."));

const configSchema = z.record(z.string().max(60), z.unknown()).refine((c) => Object.keys(c).length <= 50, "Too many config keys.");

export const ChannelCreateBody = z.object({
  type: z.enum(CHANNEL_TYPES),
  name: nameSchema,
  externalId: z.string().trim().max(200).nullish(),
  config: configSchema.optional(),
  secrets: z.record(z.string().max(60), z.string().max(2000)).optional(),
  /** Telegram: call setWebhook with the generated URL + secret (explicit external action). */
  registerWebhook: z.boolean().optional(),
});
export type ChannelCreateInput = z.infer<typeof ChannelCreateBody>;

export const ChannelPatchBody = z.object({
  name: nameSchema.optional(),
  status: z.enum(["active", "paused"]).optional(),
  externalId: z.string().trim().max(200).nullish(),
  /** Shallow merge; `null` removes a key. */
  config: z.record(z.string().max(60), z.unknown()).optional(),
  /** Merge; `null` removes a secret. */
  secrets: z.record(z.string().max(60), z.string().max(2000).nullable()).optional(),
  /** Regenerate these server-generated secrets (returned once). */
  rotate: z.array(z.enum(GENERATABLE_SECRETS)).max(3).optional(),
  /** Issue a new webhook URL token (old URL stops working immediately). */
  rotateWebhookToken: z.boolean().optional(),
  registerWebhook: z.boolean().optional(),
});
export type ChannelPatchInput = z.infer<typeof ChannelPatchBody>;

export type ChannelSetup = {
  externalId: string | null;
  config: Record<string, unknown>;
  secrets: ChannelSecrets;
  /** Secrets generated by the server in this request — shown to the admin once. */
  generated: ChannelSecrets;
};

const fail = (message: string, field?: string) => unprocessable(message, field ? [{ path: field, message }] : undefined);

/** Shown to admins when TELEGRAM_API_ID / TELEGRAM_API_HASH are missing (users never enter them). */
export const TELEGRAM_NOT_CONFIGURED =
  "Telegram isn't set up on this server yet. An admin must add TELEGRAM_API_ID and TELEGRAM_API_HASH to .env.local and restart the server. See docs/CONNECTORS_SETUP.md.";

/**
 * Telegram account channels always use the server's TELEGRAM_API_ID / TELEGRAM_API_HASH.
 * A request that tries to set per-channel credentials is rejected with 400.
 */
export function rejectTelegramCredentials(config: Record<string, unknown> | undefined, secrets: Record<string, unknown> | undefined) {
  const keys = [
    ...LEGACY_TELEGRAM_CONFIG_KEYS.filter((k) => config?.[k] !== undefined && config?.[k] !== null && config?.[k] !== "").map((k) => `config.${k}`),
    ...LEGACY_TELEGRAM_SECRET_KEYS.filter((k) => secrets?.[k] !== undefined && secrets?.[k] !== null && secrets?.[k] !== "").map((k) => `secrets.${k}`),
  ];
  if (keys.length) {
    throw badRequest(
      "Per-channel Telegram credentials are not supported. Infera uses the server's TELEGRAM_API_ID and TELEGRAM_API_HASH — remove api_id / api_hash from the request.",
      keys.map((path) => ({ path, message: "Per-channel Telegram credentials are not supported." })),
    );
  }
}

function checkConfig(type: ChannelType, config: Record<string, unknown>) {
  let size = 0;
  try {
    size = Buffer.byteLength(JSON.stringify(config));
  } catch {
    throw fail("config must be JSON.", "config");
  }
  if (size > MAX_CONFIG_BYTES) throw fail("config is too large (max 8 KB).", "config");
  for (const key of Object.keys(config)) {
    if (SECRET_NAMES[type].includes(key) || /secret|token|password|api_?key/i.test(key)) throw fail(`"${key}" looks like a secret — put it in "secrets", not "config".`, `config.${key}`);
  }
}

const optionalPattern = (config: Record<string, unknown>, key: string, re: RegExp, message: string) => {
  const v = config[key];
  if (v === undefined || v === null || v === "") return;
  if (typeof v !== "string" || !re.test(v.trim())) throw fail(message, `config.${key}`);
  config[key] = v.trim();
};

/**
 * Validates the complete desired state of a channel (create, or after a PATCH merge)
 * and fills in generated secrets. `generate` lists secrets to (re)generate.
 */
export function resolveChannelSetup(
  type: ChannelType,
  input: { externalId: string | null | undefined; config: Record<string, unknown>; secrets: ChannelSecrets; generate?: readonly string[] },
): ChannelSetup {
  if (type === "telegram_user") rejectTelegramCredentials(input.config, input.secrets);
  const secrets: ChannelSecrets = {};
  const generated: ChannelSecrets = {};
  const allowed = SECRET_NAMES[type];
  for (const [k, v] of Object.entries(input.secrets)) {
    if (!allowed.includes(k)) throw fail(allowed.length ? `Unknown secret "${k}" for ${type} channels. Allowed: ${allowed.join(", ")}.` : `${type} channels don't take secrets.`, `secrets.${k}`);
    const val = v.trim();
    if (val) secrets[k] = val;
  }
  const gen = (name: string) => {
    if (!allowed.includes(name)) return;
    if (!secrets[name] || input.generate?.includes(name)) {
      secrets[name] = newToken(32);
      generated[name] = secrets[name];
    }
  };
  const config = { ...input.config };
  checkConfig(type, config);
  let externalId: string | null = input.externalId?.trim() || null;

  switch (type) {
    case "whatsapp_cloud":
      if (!externalId || !/^\d{5,30}$/.test(externalId)) throw fail("externalId must be the WhatsApp phone_number_id (digits) from Meta.", "externalId");
      if (!secrets.accessToken) throw fail("secrets.accessToken (a permanent system-user token) is required.", "secrets.accessToken");
      if (secrets.appSecret) gen("verifyToken");
      else {
        if (!whatsappAppSecret()) throw fail("secrets.appSecret is required: this server has no shared WhatsApp app (WHATSAPP_APP_SECRET).", "secrets.appSecret");
        // Shared-app mode uses the server's verify token; a per-channel one would be unused.
        delete secrets.verifyToken;
      }
      break;
    case "telegram": {
      const botId = secrets.botToken ? telegramBotId(secrets.botToken) : null;
      if (!botId) throw fail("secrets.botToken must be a bot token from @BotFather (123456:ABC…).", "secrets.botToken");
      if (secrets.webhookSecret && !/^[A-Za-z0-9_-]{16,256}$/.test(secrets.webhookSecret)) throw fail("secrets.webhookSecret must be 16-256 characters of A-Z, a-z, 0-9, _ or -.", "secrets.webhookSecret");
      gen("webhookSecret");
      externalId = botId;
      break;
    }
    case "email":
      if (secrets.inboundSecret && secrets.inboundSecret.length < 16) throw fail("secrets.inboundSecret must be at least 16 characters.", "secrets.inboundSecret");
      gen("inboundSecret");
      optionalPattern(config, "address", /^[^\s@]+@[^\s@]+\.[^\s@]+$/, "config.address must be an email address.");
      break;
    case "slack":
      if (!secrets.signingSecret) throw fail("secrets.signingSecret (Slack app → Basic Information) is required.", "secrets.signingSecret");
      if (secrets.botToken && !/^xox[bpe]-/.test(secrets.botToken)) throw fail("secrets.botToken must be a Slack bot token (xoxb-…).", "secrets.botToken");
      optionalPattern(config, "teamId", /^[TE][A-Z0-9]{2,30}$/, "config.teamId must be a Slack team id (T…).");
      break;
    case "sms_twilio":
      if (!secrets.authToken) throw fail("secrets.authToken (Twilio auth token) is required.", "secrets.authToken");
      if (secrets.accountSid && !/^AC[0-9a-fA-F]{32}$/.test(secrets.accountSid)) throw fail("secrets.accountSid must look like AC followed by 32 hex characters.", "secrets.accountSid");
      optionalPattern(config, "phoneNumber", /^(whatsapp:)?\+\d{7,15}$/, "config.phoneNumber must be E.164, e.g. +14155550123 (or whatsapp:+…).");
      optionalPattern(config, "messagingServiceSid", /^MG[0-9a-fA-F]{32}$/, "config.messagingServiceSid must look like MG followed by 32 hex characters.");
      break;
    case "messenger":
    case "instagram": {
      // Official Messenger Platform: a Facebook Page (and, for Instagram, its linked professional account).
      if (!externalId || !/^\d{5,30}$/.test(externalId)) throw fail("externalId must be the Facebook Page ID (digits) — Page → About → Page transparency, or Meta Business Suite settings.", "externalId");
      if (!secrets.pageAccessToken) throw fail("secrets.pageAccessToken (a Page access token with pages_messaging" + (type === "instagram" ? ", instagram_manage_messages" : "") + ") is required.", "secrets.pageAccessToken");
      if (!secrets.appSecret) throw fail("secrets.appSecret (Meta app → App settings → Basic) is required to verify webhooks.", "secrets.appSecret");
      if (secrets.verifyToken && secrets.verifyToken.length < 16) throw fail("secrets.verifyToken must be at least 16 characters.", "secrets.verifyToken");
      gen("verifyToken");
      config.pageId = externalId;
      optionalPattern(config, "appId", /^\d{5,30}$/, "config.appId must be the Meta App ID (digits).");
      optionalPattern(config, "instagramAccountId", /^\d{5,30}$/, "config.instagramAccountId must be digits.");
      break;
    }
    case "telegram_user":
      // Credentials come only from the server env (rejected above); the user just scans a QR code.
      break;
    case "email_imap": {
      const provider = typeof config.provider === "string" ? config.provider : "custom";
      if (!["gmail", "outlook", "custom"].includes(provider)) throw fail("config.provider must be gmail, outlook or custom.", "config.provider");
      config.provider = provider;
      optionalPattern(config, "address", /^[^\s@]+@[^\s@]+\.[^\s@]+$/, "config.address must be an email address.");
      if (typeof config.address === "string") config.address = config.address.toLowerCase();
      optionalPattern(config, "imapHost", /^[a-z0-9.-]{3,255}$/i, "config.imapHost must be a host name.");
      optionalPattern(config, "smtpHost", /^[a-z0-9.-]{3,255}$/i, "config.smtpHost must be a host name.");
      if (provider === "custom" && !config.imapHost) throw fail("config.imapHost is required for a custom mailbox.", "config.imapHost");
      // Google sign-in fills the address and credentials later; an app password needs the address now.
      if (secrets.password && !config.address) throw fail("config.address is required with an app password.", "config.address");
      break;
    }
    case "linkedin":
      // Optional Unipile connector (LinkedIn has no messaging API for regular accounts).
      if (typeof config.dsn !== "string" || !/^(https?:\/\/)?[a-z0-9-]+\.unipile\.com(:\d{2,5})?\/?$/i.test(config.dsn.trim())) throw fail("config.dsn must be your Unipile DSN, e.g. api8.unipile.com:13851.", "config.dsn");
      config.dsn = config.dsn.trim().replace(/^https?:\/\//i, "").replace(/\/$/, "");
      if (!secrets.apiKey) throw fail("secrets.apiKey (Unipile access token) is required.", "secrets.apiKey");
      gen("webhookSecret");
      break;
    case "api":
    case "whatsapp_export":
      break;
  }

  // Only WhatsApp (phone_number_id) and Telegram (bot id) route by a globally unique provider id.
  // For other types a provider reference is informational and kept in config (it may legitimately repeat across workspaces).
  if (type !== "whatsapp_cloud" && type !== "telegram") {
    if (externalId) config.externalRef = cleanStr(externalId, 200);
    externalId = null;
  }
  return { externalId, config, secrets, generated };
}

/** Postgres unique violation (direct or wrapped by drizzle). */
export function isUniqueViolation(e: unknown): boolean {
  const code = (x: unknown) => (typeof x === "object" && x !== null && "code" in x ? (x as { code?: unknown }).code : undefined);
  return code(e) === "23505" || code((e as { cause?: unknown } | null)?.cause) === "23505";
}
